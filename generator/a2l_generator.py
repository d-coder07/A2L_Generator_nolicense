"""Builds ASAP2-compliant A2L file from parsed ELF and MAP data for CANoe import."""

from __future__ import annotations

import os
import re
from datetime import datetime
from utils.resource_limits import DEFAULT_MEMORY_LIMIT_MB, ResourceGuard

# ASAP2 datatype name mapping from internal ELF-parser types
_DATATYPE_MAP: dict[str, str] = {
    'UBYTE':        'UBYTE',
    'BYTE':         'SBYTE',
    'UWORD':        'UWORD',
    'WORD':         'SWORD',
    'ULONG':        'ULONG',
    'LONG':         'SLONG',
    'FLOAT32_IEEE': 'FLOAT32_IEEE',
    'FLOAT64_IEEE': 'FLOAT64_IEEE',
}

# Default physical limits per ASAP2 datatype
_TYPE_LIMITS: dict[str, tuple[float, float]] = {
    'UBYTE':        (0,              255),
    'SBYTE':        (-128,           127),
    'UWORD':        (0,              65535),
    'SWORD':        (-32768,         32767),
    'ULONG':        (0,              4294967295),
    'SLONG':        (-2147483648,    2147483647),
    'FLOAT32_IEEE': (-3.4028235e38,  3.4028235e38),
    'FLOAT64_IEEE': (-1.7976931e308, 1.7976931e308),
}

# Size in bytes per ASAP2 datatype
_TYPE_SIZE: dict[str, int] = {
    'UBYTE': 1, 'SBYTE': 1,
    'UWORD': 2, 'SWORD': 2,
    'ULONG': 4, 'SLONG': 4,
    'FLOAT32_IEEE': 4, 'FLOAT64_IEEE': 8,
}

# Scalar RECORD_LAYOUT name per ASAP2 datatype (referenced by CHARACTERISTIC)
_RECORD_LAYOUT: dict[str, str] = {
    'UBYTE':        'RL_UBYTE_VALUE',
    'SBYTE':        'RL_SBYTE_VALUE',
    'UWORD':        'RL_UWORD_VALUE',
    'SWORD':        'RL_SWORD_VALUE',
    'ULONG':        'RL_ULONG_VALUE',
    'SLONG':        'RL_SLONG_VALUE',
    'FLOAT32_IEEE': 'RL_FLOAT32_VALUE',
    'FLOAT64_IEEE': 'RL_FLOAT64_VALUE',
}

# ASAP2 FORMAT strings must be "%<total length>.<decimal places>"
_TYPE_FORMAT: dict[str, str] = {
    'UBYTE': '%3.0', 'SBYTE': '%4.0',
    'UWORD': '%5.0', 'SWORD': '%6.0',
    'ULONG': '%10.0', 'SLONG': '%11.0',
    'FLOAT32_IEEE': '%15.6', 'FLOAT64_IEEE': '%20.9',
}

# Characters allowed in an ASAP2 1.6 identifier
_IDENT_RE = re.compile(r'^[A-Za-z_][A-Za-z0-9_.\[\]]*$')


def generate_a2l(elf_data, map_data, output_path, template_path=None, selected_symbols=None,
                 advanced_mode=False,
                 if_data_tags=None, access='Read only', only_update=False,
                 memory_limit_mb=DEFAULT_MEMORY_LIMIT_MB):
    """Generate industry-standard A2L file with MEASUREMENT and CHARACTERISTIC definitions.

    selected_symbols may be a sequence of names or a {name: 'r'|'rw'} mapping that
    overrides the global access setting per variable.
    """

    guard = ResourceGuard(memory_limit_mb)
    guard.check(additional_bytes=len(elf_data) * 128, force=True, context='preparing selected variables')
    map_data = map_data or {}
    default_access = 'rw' if str(access).lower().startswith('read and') or str(access).lower().startswith('read/') else 'r'

    if isinstance(selected_symbols, dict):
        access_map = dict(selected_symbols)
        candidates = list(selected_symbols.keys())
    else:
        # The ELF symbol table is authoritative; statics are absent from most MAP files
        candidates = list(selected_symbols) if selected_symbols is not None else sorted(elf_data.keys())
        access_map = {}

    selected_symbols = [
        s for s in candidates
        if s in elf_data and s != '_enums' and elf_data[s].get('size', 0) > 0
        and _IDENT_RE.match(s)
    ]
    # Duplicate object names make CANoe discard the whole module
    selected_symbols = sorted(dict.fromkeys(selected_symbols))
    access_map = {s: access_map.get(s, default_access) for s in selected_symbols}
    writable = [s for s in selected_symbols if access_map[s] == 'rw']

    enums = elf_data.get('_enums', {})

    used_types = sorted({_to_a2l_datatype(elf_data[s].get('datatype', 'UBYTE')) for s in selected_symbols})

    lines: list[str] = []
    lines.append('ASAP2_VERSION 1 61')
    lines.append('')
    lines.append('/begin PROJECT A2LGenerator "A2L File generated by A2L Generator"')
    lines.append('')
    lines.append('  /begin HEADER "A2L Generator Output"')
    lines.append(f'    VERSION "{datetime.now().strftime("%Y-%m-%d")}"')
    lines.append('    PROJECT_NO A2LGEN001')
    lines.append('  /end HEADER')
    lines.append('')
    lines.append('  /begin MODULE A2LModule "Auto-generated Module"')
    lines.append('')
    lines.append('    /begin MOD_PAR "Generated from ELF and MAP"')
    lines.append('    /end MOD_PAR')
    lines.append('')
    # TriCore/HighTec targets are little endian
    lines.append('    /begin MOD_COMMON "Common parameters"')
    lines.append('      BYTE_ORDER MSB_LAST')
    lines.append('      ALIGNMENT_BYTE 1')
    lines.append('      ALIGNMENT_WORD 2')
    lines.append('      ALIGNMENT_LONG 4')
    lines.append('      ALIGNMENT_FLOAT32_IEEE 4')
    lines.append('      ALIGNMENT_FLOAT64_IEEE 8')
    lines.append('      DEPOSIT ABSOLUTE')
    lines.append('    /end MOD_COMMON')
    lines.append('')

    lines.extend(_build_xcp_if_data(if_data_tags))
    lines.extend(_build_record_layouts(used_types))
    lines.extend(_build_enum_tables(enums, elf_data, selected_symbols))
    lines.extend(_build_compu_methods(elf_data, selected_symbols, enums, guard))
    lines.extend(_build_measurements(elf_data, map_data, selected_symbols, access_map, enums, guard))

    if writable:
        lines.extend(_build_characteristics(elf_data, map_data, writable, enums, guard))

    lines.append('  /end MODULE')
    lines.append('')
    lines.append('/end PROJECT')

    body_bytes = sum(len(line) + 1 for line in lines) * 2
    guard.check(additional_bytes=body_bytes, force=True, context='building generated A2L text')
    body_text = '\n'.join(lines) + '\n'
    del lines

    if template_path and os.path.exists(template_path):
        guard.check(additional_bytes=os.path.getsize(template_path) * 2, force=True,
                context='loading the A2L template')
        with open(template_path, 'r', encoding='utf-8', newline='' if only_update else None) as f:
            template = f.read()
        if only_update:
            final_text = _merge_template_variable_tail(template, body_text, only_update=True)
        elif '{{A2L_BODY}}' in template:
            final_text = template.replace('{{A2L_BODY}}', body_text)
        elif '{A2L_BODY}' in template:
            final_text = template.replace('{A2L_BODY}', body_text)
        else:
            final_text = _merge_template_variable_tail(template, body_text)
    else:
        final_text = body_text

    guard.check(additional_bytes=len(final_text) * 2, force=True, context='preparing the output file')
    with open(output_path, 'w', encoding='utf-8', newline='' if only_update else None) as f:
        f.write(final_text)


def _merge_template_variable_tail(template: str, generated_body: str, only_update: bool = False) -> str:
    """Replace the variable-data tail, or append new definitions without cleaning."""
    generated_lines = generated_body.splitlines()
    module_end = _find_line(generated_lines, r'^\s*/end MODULE\s*$')
    if module_end is None:
        return generated_body

    variable_start = _find_line(
        generated_lines,
        r'^\s*/begin (?:RECORD_LAYOUT|COMPU_VTAB|COMPU_METHOD|MEASUREMENT|CHARACTERISTIC)\b',
    )
    if variable_start is None:
        variable_lines: list[str] = []
    else:
        variable_lines = generated_lines[variable_start:module_end]

    if only_update:
        block_types = r'RECORD_LAYOUT|COMPU_VTAB|COMPU_METHOD|MEASUREMENT|CHARACTERISTIC'
        existing = set(re.findall(
            rf'^\s*/begin ({block_types})\s+(\S+)', template, re.MULTILINE | re.IGNORECASE,
        ))
        existing = {(block_type.upper(), name) for block_type, name in existing}
        blocks = re.finditer(
            rf'^ * /begin ({block_types})\s+(\S+).*?^ * /end \1\b[^\n]*',
            '\n'.join(variable_lines), re.MULTILINE | re.DOTALL,
        )
        additions = [
            block.group(0) for block in blocks
            if (block.group(1).upper(), block.group(2)) not in existing
        ]
        if not additions:
            return template
        ending = re.search(r'^[ \t]*/end MODULE\b', template, re.MULTILINE | re.IGNORECASE)
        insert_at = ending.start() if ending else len(template)
        newline = '\r\n' if '\r\n' in template else '\n'
        added_text = (newline + '\n\n'.join(additions).replace('\n', newline) + newline + newline)
        return template[:insert_at] + added_text + template[insert_at:]

    template_lines = template.splitlines()
    template_module_end = _find_line(template_lines, r'^\s*/end MODULE\s*$')
    if template_module_end is None:
        return template.rstrip() + '\n\n' + '\n'.join(variable_lines) + '\n'

    # Prefer the last IF_DATA block because module configuration can contain several.
    if_data_end = _find_last_line(template_lines, r'^\s*/end IF_DATA\s*$')
    if if_data_end is None:
        variable_tail_start = _find_line(
            template_lines,
            r'^\s*/begin (?:RECORD_LAYOUT|COMPU_VTAB|COMPU_METHOD|MEASUREMENT|CHARACTERISTIC)\b',
        )
        if variable_tail_start is None or variable_tail_start > template_module_end:
            variable_tail_start = template_module_end
    else:
        variable_tail_start = if_data_end + 1

    prefix = '\n'.join(template_lines[:variable_tail_start]).rstrip()
    suffix = '\n'.join(template_lines[template_module_end:]).lstrip()
    parts = [prefix]
    if variable_lines:
        parts.append('\n'.join(variable_lines).strip())
    parts.append(suffix)
    return '\n\n'.join(part for part in parts if part) + '\n'


def _find_line(lines: list[str], pattern: str) -> int | None:
    """Return the first line matching a regular expression."""
    matcher = re.compile(pattern, re.IGNORECASE)
    for index, line in enumerate(lines):
        if matcher.match(line):
            return index
    return None


def _find_last_line(lines: list[str], pattern: str) -> int | None:
    """Return the last line matching a regular expression."""
    matcher = re.compile(pattern, re.IGNORECASE)
    matches = [index for index, line in enumerate(lines) if matcher.match(line)]
    return matches[-1] if matches else None


